DO $$
DECLARE
  table_name text;
  constraint_name text;
  current_type text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['likes', 'comments'] LOOP
    SELECT format_type(attribute.atttypid, attribute.atttypmod)
    INTO current_type
    FROM pg_attribute AS attribute
    WHERE attribute.attrelid = format('public.%I', table_name)::regclass
      AND attribute.attname = 'post_id'
      AND NOT attribute.attisdropped;

    FOR constraint_name IN
      SELECT constraint_row.conname
      FROM pg_constraint AS constraint_row
      JOIN pg_attribute AS attribute
        ON attribute.attrelid = constraint_row.conrelid
       AND attribute.attnum = ANY(constraint_row.conkey)
      WHERE constraint_row.conrelid = format('public.%I', table_name)::regclass
        AND constraint_row.contype = 'f'
        AND attribute.attname = 'post_id'
    LOOP
      EXECUTE format('ALTER TABLE public.%I DROP CONSTRAINT %I', table_name, constraint_name);
    END LOOP;

    EXECUTE format(
      'DELETE FROM public.%I AS item WHERE NOT EXISTS (SELECT 1 FROM public.posts AS post WHERE post.id::text = item.post_id::text)',
      table_name
    );

    IF current_type <> 'uuid' THEN
      EXECUTE format(
        'ALTER TABLE public.%I ALTER COLUMN post_id TYPE uuid USING post_id::text::uuid',
        table_name
      );
    END IF;

    EXECUTE format(
      'ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (post_id) REFERENCES public.posts(id) ON DELETE CASCADE',
      table_name,
      table_name || '_post_id_fkey'
    );
  END LOOP;
END
$$;


DROP FUNCTION IF EXISTS public.increment_post_share_count(bigint);
CREATE FUNCTION public.increment_post_share_count(p_post_id uuid)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  updated_count integer;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
  END IF;

  UPDATE public.posts
  SET share_count = share_count + 1
  WHERE id = p_post_id
  RETURNING share_count INTO updated_count;

  IF updated_count IS NOT NULL THEN
    PERFORM public.reward_post_engagement(p_post_id, auth.uid(), 'share', updated_count::text);
  END IF;

  RETURN updated_count;
END;
$$;
REVOKE ALL ON FUNCTION public.increment_post_share_count(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.increment_post_share_count(uuid) TO authenticated;


DROP FUNCTION IF EXISTS public.reward_post_engagement(bigint, uuid, text, text);
CREATE OR REPLACE FUNCTION public.reward_post_engagement(
  p_post_id uuid,
  p_actor_id uuid,
  p_event_type text,
  p_event_id text DEFAULT ''
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
  CREATE TABLE IF NOT EXISTS public.likes_legacy_archive AS
  SELECT likes.*, now() AS archived_at
  FROM public.likes AS likes
  WHERE false;
  CREATE TABLE IF NOT EXISTS public.comments_legacy_archive AS
  SELECT comments.*, now() AS archived_at
  FROM public.comments AS comments
  WHERE false;

  ALTER TABLE public.likes_legacy_archive ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.comments_legacy_archive ENABLE ROW LEVEL SECURITY;
  REVOKE ALL ON public.likes_legacy_archive, public.comments_legacy_archive FROM anon, authenticated;
AS $$
DECLARE
  post_owner_id uuid;
  event_key text;
  reward_inserted boolean;
BEGIN
  IF p_event_type NOT IN ('like', 'view', 'comment', 'share') THEN
    RAISE EXCEPTION 'Unsupported reward event.';
  END IF;
  IF p_actor_id IS NULL OR auth.uid() IS DISTINCT FROM p_actor_id THEN
    RETURN;
  END IF;

  SELECT user_id INTO post_owner_id
  FROM public.posts
  WHERE id = p_post_id;
  IF post_owner_id IS NULL OR post_owner_id = p_actor_id THEN
    RETURN;
  END IF;

  event_key := p_event_type || ':' || p_post_id::text || ':' || p_actor_id::text;
  IF p_event_type IN ('comment', 'share') THEN
    IF p_event_id IS NULL OR length(p_event_id) = 0 THEN
      RAISE EXCEPTION 'Reward event ID is required.';
    END IF;
    event_key := event_key || ':' || p_event_id;
  END IF;

  INSERT INTO public.reward_ledger (event_key, user_id, blue_points_delta, amount_delta)
  VALUES (event_key, post_owner_id, 1, 0.10)
  ON CONFLICT (event_key) DO NOTHING
  RETURNING true INTO reward_inserted;

  IF reward_inserted THEN
    INSERT INTO public.accounts (id, balance, blue_points)
    VALUES (post_owner_id, 0.10, 1)
    ON CONFLICT (id) DO UPDATE
    SET balance = public.accounts.balance + 0.10,
        blue_points = public.accounts.blue_points + 1;
  END IF;
END;
$$;
REVOKE ALL ON FUNCTION public.reward_post_engagement(uuid, uuid, text, text) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.sync_post_like_count()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target_post_id uuid;
BEGIN
  target_post_id := CASE WHEN TG_OP = 'INSERT' THEN NEW.post_id ELSE OLD.post_id END;
  UPDATE public.posts
  SET likes = GREATEST(0, likes + CASE WHEN TG_OP = 'INSERT' THEN 1 ELSE -1 END)
  WHERE id = target_post_id;
  RETURN NULL;
END;
$$;

CREATE TRIGGER sync_post_like_count
  AFTER INSERT OR DELETE ON public.likes
  FOR EACH ROW EXECUTE FUNCTION public.sync_post_like_count();


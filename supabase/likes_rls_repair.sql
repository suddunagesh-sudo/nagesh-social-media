BEGIN;

CREATE TABLE IF NOT EXISTS public.likes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id bigint NOT NULL,
  user_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.likes
  ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS post_id bigint,
  ADD COLUMN IF NOT EXISTS user_id uuid,
  ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();

DELETE FROM public.likes AS liked
WHERE liked.post_id IS NULL
   OR liked.user_id IS NULL
   OR NOT EXISTS (
     SELECT 1 FROM public.posts AS post
     WHERE post.id::text = liked.post_id::text
   )
   OR NOT EXISTS (
     SELECT 1 FROM auth.users AS auth_user
     WHERE auth_user.id::text = liked.user_id::text
   );

WITH ranked_likes AS (
  SELECT ctid,
         row_number() OVER (
           PARTITION BY post_id, user_id
           ORDER BY created_at DESC NULLS LAST, ctid DESC
         ) AS row_number
  FROM public.likes
)
DELETE FROM public.likes AS liked
USING ranked_likes
WHERE liked.ctid = ranked_likes.ctid
  AND ranked_likes.row_number > 1;

ALTER TABLE public.likes
  ALTER COLUMN post_id SET NOT NULL,
  ALTER COLUMN user_id SET NOT NULL,
  ALTER COLUMN created_at SET DEFAULT now();

CREATE UNIQUE INDEX IF NOT EXISTS likes_id_uidx ON public.likes (id);
CREATE UNIQUE INDEX IF NOT EXISTS likes_post_id_user_id_uidx ON public.likes (post_id, user_id);

DO $$
DECLARE
  constraint_row record;
BEGIN
  FOR constraint_row IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.likes'::regclass
      AND contype = 'f'
  LOOP
    EXECUTE format('ALTER TABLE public.likes DROP CONSTRAINT %I', constraint_row.conname);
  END LOOP;

  ALTER TABLE public.likes
    ADD CONSTRAINT likes_post_id_fkey
      FOREIGN KEY (post_id) REFERENCES public.posts(id) ON DELETE CASCADE,
    ADD CONSTRAINT likes_user_id_fkey
      FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE;
END;
$$;

ALTER TABLE public.likes ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
  policy_row record;
BEGIN
  FOR policy_row IN
    SELECT policyname
    FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'likes'
  LOOP
    EXECUTE format('DROP POLICY %I ON public.likes', policy_row.policyname);
  END LOOP;
END;
$$;

CREATE POLICY likes_select_own
  ON public.likes FOR SELECT TO authenticated
  USING (auth.uid() = user_id);
CREATE POLICY likes_insert_own
  ON public.likes FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);
CREATE POLICY likes_delete_own
  ON public.likes FOR DELETE TO authenticated
  USING (auth.uid() = user_id);

GRANT SELECT, INSERT, DELETE ON public.likes TO authenticated;
DO $$
DECLARE
  likes_id_sequence text;
BEGIN
  likes_id_sequence := pg_get_serial_sequence('public.likes', 'id');
  IF likes_id_sequence IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', likes_id_sequence);
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.sync_post_like_count()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target_post_id bigint;
BEGIN
  target_post_id := CASE WHEN TG_OP = 'INSERT' THEN NEW.post_id ELSE OLD.post_id END;
  UPDATE public.posts
  SET likes = GREATEST(0, likes + CASE WHEN TG_OP = 'INSERT' THEN 1 ELSE -1 END)
  WHERE id = target_post_id;
  RETURN NULL;
END;
$$;

UPDATE public.posts AS post
SET likes = (
  SELECT count(*)::integer
  FROM public.likes AS liked
  WHERE liked.post_id = post.id
);

DROP TRIGGER IF EXISTS sync_post_like_count ON public.likes;
CREATE TRIGGER sync_post_like_count
  AFTER INSERT OR DELETE ON public.likes
  FOR EACH ROW EXECUTE FUNCTION public.sync_post_like_count();

COMMIT;